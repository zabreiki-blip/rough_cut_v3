"""Reproducible-dependency contract: input files, hashed uv locks, Dockerfile, CI."""

from __future__ import annotations

import os
from pathlib import Path
import re

from packaging.requirements import Requirement
from packaging.version import Version
import pytest

ROOT = Path(__file__).resolve().parents[1]

RUNTIME_LOCK = "requirements-lock.txt"
DEV_LOCK = "requirements-dev-lock.txt"
DEV_ONLY_TOOLS = {"pytest", "pytest-cov", "pytest-timeout", "ruff", "mypy", "coverage"}


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name.lower())


def _read(filename: str) -> str:
    return (ROOT / filename).read_text(encoding="utf-8")


def _direct_requirements(filename: str) -> list[Requirement]:
    """Requirements declared in an input file (``-r`` includes are not followed)."""
    result = []
    for raw in _read(filename).splitlines():
        line = raw.split("#", 1)[0].strip()
        if line and not line.startswith("-"):
            result.append(Requirement(line))
    return result


def _lock_entries(filename: str) -> dict[str, list[tuple[str, int]]]:
    """name -> [(version, hash_count)] for every ``pkg==ver`` entry of a hashed lock."""
    entries: dict[str, list[tuple[str, int]]] = {}
    lines = _read(filename).splitlines()
    for index, line in enumerate(lines):
        match = re.match(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;\\]+)", line)
        if not match:
            continue
        hashes = 0
        for follow in lines[index + 1 :]:
            if follow.strip().startswith("--hash=sha256:"):
                hashes += 1
            else:
                break
        entries.setdefault(_norm(match.group(1)), []).append((match.group(2), hashes))
    return entries


def _versions(filename: str, name: str) -> set[str]:
    return {version for version, _ in _lock_entries(filename).get(_norm(name), [])}


def test_lock_files_exist_and_are_generated_by_uv() -> None:
    for filename in (RUNTIME_LOCK, DEV_LOCK):
        text = _read(filename)
        assert "autogenerated by uv" in text, f"{filename} must be generated, not hand-edited"
        assert "scripts/lock-deps" in text, f"{filename} header must name the regeneration script"


@pytest.mark.parametrize("filename", [RUNTIME_LOCK, DEV_LOCK])
def test_every_lock_entry_is_pinned_and_hashed(filename: str) -> None:
    entries = _lock_entries(filename)
    assert len(entries) > 20
    for name, variants in entries.items():
        for version, hashes in variants:
            assert hashes >= 1, f"{filename}: {name}=={version} has no --hash"
    # Nothing unpinned or unhashed may sneak in as a bare requirement line.
    for raw in _read(filename).splitlines():
        if raw and not raw.startswith((" ", "#")) and not raw.startswith("-"):
            assert re.match(r"^[A-Za-z0-9][A-Za-z0-9._-]*==", raw), f"{filename}: {raw!r}"


def test_runtime_inputs_are_fully_covered_by_runtime_lock() -> None:
    declared = _direct_requirements("requirements.txt") + _direct_requirements(
        "requirements-whisper.txt"
    )
    assert {_norm(r.name) for r in declared} >= {
        "flask",
        "pillow",
        "python-dotenv",
        "faster-whisper",
    }
    for requirement in declared:
        versions = _versions(RUNTIME_LOCK, requirement.name)
        assert versions, f"{requirement.name} is not locked in {RUNTIME_LOCK}"
        for version in versions:
            # ``==`` pins must match exactly; ranges (Pillow>=10, faster-whisper<2, ...)
            # must be resolved to a concrete version inside the range.
            assert requirement.specifier.contains(version), (
                f"{requirement.name}=={version} in {RUNTIME_LOCK} violates {requirement.specifier}"
            )
        if "==" in str(requirement.specifier):
            exact = str(requirement.specifier).removeprefix("==")
            assert versions == {exact}


def test_runtime_lock_excludes_dev_tooling() -> None:
    locked = set(_lock_entries(RUNTIME_LOCK))
    assert not (locked & DEV_ONLY_TOOLS), locked & DEV_ONLY_TOOLS
    assert "pre-commit" not in locked and "virtualenv" not in locked


def test_dev_lock_covers_direct_dev_and_runtime_dependencies() -> None:
    dev_direct = [
        r for r in _direct_requirements("requirements-dev.txt") if _norm(r.name) in DEV_ONLY_TOOLS
    ]
    assert {_norm(r.name) for r in dev_direct} >= {"pytest", "ruff", "mypy"}
    for requirement in dev_direct + _direct_requirements("requirements.txt"):
        versions = _versions(DEV_LOCK, requirement.name)
        assert versions, f"{requirement.name} is not locked in {DEV_LOCK}"
        assert all(requirement.specifier.contains(v) for v in versions)


def test_dev_lock_shares_runtime_versions_with_runtime_lock() -> None:
    runtime = _lock_entries(RUNTIME_LOCK)
    dev = _lock_entries(DEV_LOCK)
    shared = set(runtime) & set(dev)
    assert {"flask", "requests", "gunicorn", "pillow"} <= shared
    for name in shared:
        assert {v for v, _ in runtime[name]} & {v for v, _ in dev[name]}, (
            f"{name}: CI verify tests a different version than Docker ships"
        )


def test_dev_tools_are_patched_and_pre_commit_is_not_a_dependency() -> None:
    # PYSEC-2026-1845: pytest tmpdir issue fixed in 9.0.3 (no fixed 8.x exists).
    assert _versions(DEV_LOCK, "pytest")
    assert all(Version(v) >= Version("9.0.3") for v in _versions(DEV_LOCK, "pytest"))
    pytest_spec = next(
        r for r in _direct_requirements("requirements-dev.txt") if r.name == "pytest"
    )
    assert pytest_spec.specifier.contains("9.0.3") and not pytest_spec.specifier.contains("8.3.5")
    # pre-commit is an optional local tool (README), not a locked project dependency.
    assert "pre-commit" not in _lock_entries(DEV_LOCK)
    assert "virtualenv" not in _lock_entries(DEV_LOCK)


def test_dockerfile_installs_only_the_hashed_runtime_lock() -> None:
    dockerfile = _read("Dockerfile")
    assert re.search(r"^COPY requirements-lock\.txt \.$", dockerfile, re.M)
    assert re.search(
        r"^RUN pip install --no-cache-dir --require-hashes -r requirements-lock\.txt$",
        dockerfile,
        re.M,
    )
    instructions = "\n".join(
        line for line in dockerfile.splitlines() if not line.lstrip().startswith("#")
    )
    installs = re.findall(r"pip install[^\n]*", instructions)
    assert len(installs) == 1, installs
    for floating in ("requirements.txt", "requirements-whisper.txt", "requirements-dev"):
        assert floating not in instructions


def test_ci_installs_hashed_locks() -> None:
    workflow = _read(".github/workflows/ci.yml")
    verify = re.search(r"^  verify:\n(?P<job>.*?)(?=^  \S|\Z)", workflow, re.M | re.S)
    smoke = re.search(r"^  runtime-smoke:\n(?P<job>.*?)(?=^  \S|\Z)", workflow, re.M | re.S)
    audit = re.search(r"^  dependency-audit:\n(?P<job>.*?)(?=^  \S|\Z)", workflow, re.M | re.S)
    assert verify and smoke and audit
    assert "python -m pip install --require-hashes -r requirements-dev-lock.txt" in verify["job"]
    assert "requirements-dev-lock.txt" in verify["job"].split("cache-dependency-path")[1]
    assert "-r requirements-dev.txt" not in verify["job"]
    cache = smoke["job"].split("cache-dependency-path")[1].split("- name")[0]
    assert "requirements-lock.txt" in cache
    assert "requirements-lock.txt" in audit["job"].split("cache-dependency-path")[1]


def test_lock_script_regenerates_both_locks_with_uv() -> None:
    script = ROOT / "scripts/lock-deps"
    assert script.is_file() and os.access(script, os.X_OK)
    text = script.read_text(encoding="utf-8")
    assert "uv pip compile" in text
    assert "--python-version 3.11" in text
    assert "--universal" in text
    assert "--generate-hashes" in text
    assert "requirements.txt requirements-whisper.txt" in text
    assert "-o requirements-lock.txt" in text
    assert "requirements-dev.txt" in text and "-o requirements-dev-lock.txt" in text


def test_dependency_policy_documents_lock_workflow() -> None:
    policy = _read("docs/DEPENDENCY_POLICY.md")
    for needle in ("scripts/lock-deps", "requirements-lock.txt", "requirements-dev-lock.txt"):
        assert needle in policy
    assert "pip freeze" not in _read("README.md")
